-- =====================================================================
-- Tienda Don Julio - Esquema de la base de datos (PostgreSQL)
-- Se ejecuta automáticamente la PRIMERA vez que arranca el contenedor
-- de Postgres con el volumen vacío (docker-entrypoint-initdb.d).
-- Los nombres siguen el diagrama del modelo relacional (database/).
-- Todo en minúsculas y sin tildes/ñ para no tener que usar comillas.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- cliente: única tabla de cuentas (clientes y trabajadores).
-- Reemplaza a la antigua tabla "Usuarios" (decisión 1 del sprint 4).
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente  VARCHAR(100) NOT NULL,
    cedula          VARCHAR(20)  NOT NULL,
    telefono        VARCHAR(20),
    email           VARCHAR(100) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,           -- hash BCrypt, nunca texto plano
    rol             VARCHAR(20)  NOT NULL DEFAULT 'Cliente'
                    CHECK (rol IN ('Cliente', 'Trabajador')),
    fecha_creacion  TIMESTAMP    NOT NULL DEFAULT now()
);

-- La cédula es única, salvo el valor de relleno '00000000' que AuthService usa
-- cuando el cliente no la escribe al registrarse.
CREATE UNIQUE INDEX uq_cliente_cedula ON cliente (cedula) WHERE cedula <> '00000000';

CREATE TABLE producto (
    id_producto     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR(100)  NOT NULL,
    precio_ventas   NUMERIC(10,2) NOT NULL CHECK (precio_ventas >= 0),
    precio_compra   NUMERIC(10,2) NOT NULL CHECK (precio_compra >= 0),
    stock           INTEGER       NOT NULL DEFAULT 0 CHECK (stock >= 0)   -- la BD impide stock negativo
);

-- ---------------------------------------------------------------------
-- pedido: lo crea el cliente; el trabajador cambia su estado.
-- ---------------------------------------------------------------------
CREATE TABLE pedido (
    id_pedido   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  INTEGER       NOT NULL REFERENCES cliente (id_cliente),
    fecha       TIMESTAMP     NOT NULL DEFAULT now(),
    estado      VARCHAR(20)   NOT NULL DEFAULT 'Pendiente'
                CHECK (estado IN ('Pendiente', 'EnProceso', 'Completado', 'Cancelado')),
    total       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0)
);

-- Líneas del pedido (en el código es la entidad CartItem).
CREATE TABLE carrito_items (
    id_carrito_items INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido        INTEGER NOT NULL REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    id_producto      INTEGER NOT NULL REFERENCES producto (id_producto),
    cantidad         INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (precio_unitario >= 0)  -- precio al crear el pedido
);

-- ---------------------------------------------------------------------
-- venta: se registra cuando el pedido se confirma (o en venta de mostrador).
-- id_cliente = quien compró (NULL en venta de mostrador).
-- id_usuario = cuenta (trabajador) que procesó la venta; puede ser NULL.
-- ---------------------------------------------------------------------
CREATE TABLE venta (
    id_venta    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  INTEGER REFERENCES cliente (id_cliente),
    id_usuario  INTEGER REFERENCES cliente (id_cliente),
    fecha_venta TIMESTAMP     NOT NULL DEFAULT now(),
    total       NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    total_costo NUMERIC(10,2) NOT NULL CHECK (total_costo >= 0),
    ganancia    NUMERIC(10,2) NOT NULL
);

CREATE TABLE detalle_venta (
    id_detalle_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta         INTEGER       NOT NULL REFERENCES venta (id_venta) ON DELETE CASCADE,
    id_producto      INTEGER       NOT NULL REFERENCES producto (id_producto),
    nombre_producto  VARCHAR(100)  NOT NULL,   -- copia del nombre al momento de la venta
    cantidad         INTEGER       NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    costo_unitario   NUMERIC(10,2) NOT NULL CHECK (costo_unitario >= 0)
);

-- ---------------------------------------------------------------------
-- movimiento: libro de caja (ingresos, gastos, compras de inventario).
-- ---------------------------------------------------------------------
CREATE TABLE movimiento (
    id_movimiento    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       INTEGER REFERENCES cliente (id_cliente),
    fecha_movimiento TIMESTAMP     NOT NULL DEFAULT now(),
    tipo             VARCHAR(20)   NOT NULL
                     CHECK (tipo IN ('Ingreso', 'Gasto', 'CompraInventario')),
    descripcion      VARCHAR(200)  NOT NULL DEFAULT '',
    monto            NUMERIC(10,2) NOT NULL CHECK (monto > 0)
);

-- Índices para las consultas más frecuentes (pedidos del cliente, panel del
-- trabajador, reporte de más vendidos y balance por fechas).
CREATE INDEX idx_pedido_cliente        ON pedido (id_cliente);
CREATE INDEX idx_pedido_estado         ON pedido (estado);
CREATE INDEX idx_carrito_items_pedido  ON carrito_items (id_pedido);
CREATE INDEX idx_detalle_venta_venta   ON detalle_venta (id_venta);
CREATE INDEX idx_detalle_venta_producto ON detalle_venta (id_producto);
CREATE INDEX idx_venta_fecha           ON venta (fecha_venta);
CREATE INDEX idx_venta_cliente         ON venta (id_cliente);
CREATE INDEX idx_movimiento_fecha      ON movimiento (fecha_movimiento);

COMMIT;
